-- Initial schema (PostgreSQL). Mirrors the JPA entities; Hibernate runs with ddl-auto=validate in prod.

create table users (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null,
    password_hash varchar(255) not null,
    full_name     varchar(100) not null,
    phone         varchar(20),
    role          varchar(20)  not null check (role in ('STAFF','KITCHEN','MANAGER')),
    is_active     boolean      not null,
    constraint uk_users_username unique (username)
);

create table categories (
    id         bigint generated by default as identity primary key,
    name       varchar(100) not null,
    sort_order integer      not null
);

create table menu_items (
    id           bigint generated by default as identity primary key,
    category_id  bigint        not null,
    name         varchar(120)  not null,
    description  varchar(500),
    price        numeric(12,2) not null,
    image_url    varchar(255),
    is_available boolean       not null,
    created_at   timestamp(6)  not null,
    constraint fk_menu_items_category foreign key (category_id) references categories (id)
);

create table restaurant_tables (
    id       bigint generated by default as identity primary key,
    code     varchar(20) not null,
    seats    integer     not null,
    qr_token varchar(64) not null,
    status   varchar(20) not null check (status in ('FREE','OCCUPIED')),
    constraint uk_tables_code unique (code),
    constraint uk_tables_qr_token unique (qr_token)
);

create table vouchers (
    id             bigint generated by default as identity primary key,
    code           varchar(40)   not null,
    discount_type  varchar(20)   not null check (discount_type in ('PERCENT','AMOUNT')),
    discount_value numeric(12,2) not null,
    min_order      numeric(12,2) not null,
    start_at       timestamp(6),
    end_at         timestamp(6),
    usage_limit    integer check (usage_limit >= 0),
    constraint uk_vouchers_code unique (code)
);

create table orders (
    id           bigint generated by default as identity primary key,
    table_id     bigint        not null,
    staff_id     bigint,
    voucher_id   bigint,
    status       varchar(20)   not null check (status in ('PENDING','CONFIRMED','COOKING','SERVED','COMPLETED','CANCELLED')),
    note         varchar(255),
    total_amount numeric(12,2) not null,
    created_at   timestamp(6)  not null,
    updated_at   timestamp(6)  not null,
    constraint fk_orders_table   foreign key (table_id)   references restaurant_tables (id),
    constraint fk_orders_staff   foreign key (staff_id)   references users (id),
    constraint fk_orders_voucher foreign key (voucher_id) references vouchers (id)
);

create table order_items (
    id           bigint generated by default as identity primary key,
    order_id     bigint        not null,
    menu_item_id bigint        not null,
    quantity     integer       not null,
    unit_price   numeric(12,2) not null,
    note         varchar(255),
    status       varchar(20)   not null check (status in ('PENDING','COOKING','READY','SERVED','CANCELLED')),
    constraint fk_order_items_order     foreign key (order_id)     references orders (id),
    constraint fk_order_items_menu_item foreign key (menu_item_id) references menu_items (id)
);

create table payments (
    id       bigint generated by default as identity primary key,
    order_id bigint        not null,
    method   varchar(20)   not null check (method in ('CASH','TRANSFER','EWALLET')),
    amount   numeric(12,2) not null,
    status   varchar(20)   not null check (status in ('PENDING','PAID','FAILED')),
    paid_at  timestamp(6),
    constraint fk_payments_order foreign key (order_id) references orders (id)
);

create table reviews (
    id           bigint generated by default as identity primary key,
    order_id     bigint       not null,
    menu_item_id bigint       not null,
    rating       integer      not null,
    comment      varchar(500),
    created_at   timestamp(6) not null,
    constraint fk_reviews_order     foreign key (order_id)     references orders (id),
    constraint fk_reviews_menu_item foreign key (menu_item_id) references menu_items (id),
    constraint uk_reviews_order_item unique (order_id, menu_item_id)
);

create table service_requests (
    id         bigint generated by default as identity primary key,
    table_id   bigint       not null,
    type       varchar(20)  not null check (type in ('WATER','HELP','BILL','OTHER')),
    status     varchar(20)  not null check (status in ('OPEN','DONE')),
    created_at timestamp(6) not null,
    constraint fk_service_requests_table foreign key (table_id) references restaurant_tables (id)
);

-- Indexes for foreign keys and the status filters used by the staff/kitchen screens and reports.
create index ix_menu_items_category     on menu_items (category_id);
create index ix_orders_table_status     on orders (table_id, status);
create index ix_orders_status_updated   on orders (status, updated_at);
create index ix_orders_staff            on orders (staff_id);
create index ix_orders_voucher          on orders (voucher_id);
create index ix_order_items_order       on order_items (order_id);
create index ix_order_items_menu_item   on order_items (menu_item_id);
create index ix_payments_order          on payments (order_id);
create index ix_reviews_menu_item       on reviews (menu_item_id);
create index ix_service_requests_status on service_requests (status, created_at);
create index ix_service_requests_table  on service_requests (table_id);
