-- Atlas Restaurant – home-delivery ordering, PostgreSQL schema (3NF).
-- Conventions: surrogate bigint identity keys, snake_case, named constraints, every FK indexed,
-- enumerations as varchar + CHECK, money as numeric(12,2) in VND.

-- ---------------------------------------------------------------- people
create table users (
    id            bigint generated by default as identity primary key,
    full_name     varchar(100) not null,
    phone         varchar(15)  not null,
    email         varchar(120),
    password_hash varchar(100) not null,
    role          varchar(20)  not null,
    is_active     boolean      not null default true,
    created_at    timestamp(6) not null,
    constraint uk_users_phone unique (phone),
    constraint uk_users_email unique (email),
    constraint ck_users_role  check (role in ('CUSTOMER','STAFF','KITCHEN','MANAGER')),
    constraint ck_users_phone check (phone ~ '^[0-9]{9,15}$')
);

-- Districts the restaurant delivers to, each with its own fee and delivery time.
create table delivery_zones (
    id                bigint generated by default as identity primary key,
    name              varchar(60)   not null,
    delivery_fee      numeric(12,2) not null,
    estimated_minutes integer       not null,
    sort_order        integer       not null default 0,
    is_active         boolean       not null default true,
    constraint uk_delivery_zones_name unique (name),
    constraint ck_delivery_zones_fee check (delivery_fee >= 0),
    constraint ck_delivery_zones_eta check (estimated_minutes between 5 and 240)
);

-- A customer's saved delivery addresses (address book). Deleted with the user.
create table addresses (
    id              bigint generated by default as identity primary key,
    user_id         bigint       not null,
    zone_id         bigint       not null,
    label           varchar(40)  not null,
    recipient_name  varchar(100) not null,
    recipient_phone varchar(15)  not null,
    street          varchar(200) not null,
    note            varchar(200),
    is_default      boolean      not null default false,
    created_at      timestamp(6) not null,
    constraint fk_addresses_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_addresses_zone foreign key (zone_id) references delivery_zones (id),
    constraint ck_addresses_phone check (recipient_phone ~ '^[0-9]{9,15}$')
);
create index ix_addresses_user on addresses (user_id);
create index ix_addresses_zone on addresses (zone_id);
create unique index ux_addresses_one_default on addresses (user_id) where is_default;

-- ---------------------------------------------------------------- menu
create table categories (
    id         bigint generated by default as identity primary key,
    name       varchar(60)  not null,
    image_url  varchar(500),
    sort_order integer      not null default 0,
    constraint uk_categories_name unique (name)
);

create table menu_items (
    id           bigint generated by default as identity primary key,
    category_id  bigint        not null,
    name         varchar(120)  not null,
    description  varchar(500),
    price        numeric(12,2) not null,
    image_url    varchar(500),
    is_available boolean       not null default true,   -- in stock today (kitchen toggles)
    is_active    boolean       not null default true,   -- still on the menu (archived instead of deleted)
    created_at   timestamp(6)  not null,
    updated_at   timestamp(6)  not null,
    constraint uk_menu_items_name unique (name),
    constraint fk_menu_items_category foreign key (category_id) references categories (id),
    constraint ck_menu_items_price check (price >= 0)
);
create index ix_menu_items_category on menu_items (category_id);

create table favorites (
    user_id      bigint       not null,
    menu_item_id bigint       not null,
    created_at   timestamp(6) not null,
    constraint pk_favorites primary key (user_id, menu_item_id),
    constraint fk_favorites_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_favorites_menu_item foreign key (menu_item_id) references menu_items (id) on delete cascade
);
create index ix_favorites_menu_item on favorites (menu_item_id);

-- Server-side cart: survives app restarts and follows the customer across devices.
create table cart_items (
    user_id      bigint       not null,
    menu_item_id bigint       not null,
    quantity     integer      not null,
    note         varchar(200),
    updated_at   timestamp(6) not null,
    constraint pk_cart_items primary key (user_id, menu_item_id),
    constraint fk_cart_items_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_cart_items_menu_item foreign key (menu_item_id) references menu_items (id) on delete cascade,
    constraint ck_cart_items_quantity check (quantity between 1 and 99)
);
create index ix_cart_items_menu_item on cart_items (menu_item_id);

-- ---------------------------------------------------------------- promotions
create table vouchers (
    id              bigint generated by default as identity primary key,
    code            varchar(40)   not null,
    description     varchar(200),
    discount_type   varchar(10)   not null,
    discount_value  numeric(12,2) not null,
    max_discount    numeric(12,2),
    min_order       numeric(12,2) not null default 0,
    start_at        timestamp(6),
    end_at          timestamp(6),
    usage_limit     integer,
    per_user_limit  integer,
    is_active       boolean       not null default true,
    created_at      timestamp(6)  not null,
    constraint uk_vouchers_code unique (code),
    constraint ck_vouchers_type check (discount_type in ('PERCENT','AMOUNT')),
    constraint ck_vouchers_value check (discount_value > 0 and (discount_type <> 'PERCENT' or discount_value <= 100)),
    constraint ck_vouchers_max check (max_discount is null or max_discount > 0),
    constraint ck_vouchers_min_order check (min_order >= 0),
    constraint ck_vouchers_period check (start_at is null or end_at is null or end_at > start_at),
    constraint ck_vouchers_limits check ((usage_limit is null or usage_limit > 0) and (per_user_limit is null or per_user_limit > 0))
);

-- ---------------------------------------------------------------- orders
-- Delivery details are copied from the address book when ordering: they are facts of this delivery and must not
-- change when the customer later edits or deletes the address. delivery_fee and discount_amount are the amounts
-- charged at that moment. Subtotal and total are always computed from order_items and never stored.
create table orders (
    id               bigint generated by default as identity primary key,
    customer_id      bigint        not null,
    zone_id          bigint        not null,
    voucher_id       bigint,
    status           varchar(20)   not null,
    recipient_name   varchar(100)  not null,
    recipient_phone  varchar(15)   not null,
    delivery_street  varchar(200)  not null,
    delivery_note    varchar(200),
    note             varchar(300),
    delivery_fee     numeric(12,2) not null,
    discount_amount  numeric(12,2) not null default 0,
    payment_method   varchar(10)   not null default 'COD',
    created_at       timestamp(6)  not null,
    updated_at       timestamp(6)  not null,
    version          bigint        not null default 0,
    constraint fk_orders_customer foreign key (customer_id) references users (id),
    constraint fk_orders_zone foreign key (zone_id) references delivery_zones (id),
    constraint fk_orders_voucher foreign key (voucher_id) references vouchers (id),
    constraint ck_orders_status check (status in ('PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED')),
    constraint ck_orders_payment check (payment_method in ('COD')),
    constraint ck_orders_amounts check (delivery_fee >= 0 and discount_amount >= 0),
    constraint ck_orders_phone check (recipient_phone ~ '^[0-9]{9,15}$')
);
create index ix_orders_customer_created on orders (customer_id, created_at desc);
create index ix_orders_status_created on orders (status, created_at);
create index ix_orders_zone on orders (zone_id);
create index ix_orders_voucher on orders (voucher_id);

-- unit_price is the price charged when the order was placed (menu prices change later).
create table order_items (
    id           bigint generated by default as identity primary key,
    order_id     bigint        not null,
    menu_item_id bigint        not null,
    quantity     integer       not null,
    unit_price   numeric(12,2) not null,
    note         varchar(200),
    constraint fk_order_items_order foreign key (order_id) references orders (id),
    constraint fk_order_items_menu_item foreign key (menu_item_id) references menu_items (id),
    constraint ck_order_items_quantity check (quantity between 1 and 99),
    constraint ck_order_items_price check (unit_price >= 0)
);
create index ix_order_items_order on order_items (order_id);
create index ix_order_items_menu_item on order_items (menu_item_id);

-- Audit trail of every status change (the tracking timeline). changed_by is null for system actions.
create table order_status_history (
    id         bigint generated by default as identity primary key,
    order_id   bigint       not null,
    status     varchar(20)  not null,
    changed_by bigint,
    note       varchar(300),
    changed_at timestamp(6) not null,
    constraint fk_order_status_history_order foreign key (order_id) references orders (id),
    constraint fk_order_status_history_user foreign key (changed_by) references users (id),
    constraint ck_order_status_history_status check (status in ('PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED'))
);
create index ix_order_status_history_order on order_status_history (order_id, changed_at);
create index ix_order_status_history_user on order_status_history (changed_by);

-- One review per order line, after the order was delivered. The customer and dish are reached through the line.
create table reviews (
    id            bigint generated by default as identity primary key,
    order_item_id bigint       not null,
    rating        integer      not null,
    comment       varchar(500),
    created_at    timestamp(6) not null,
    constraint uk_reviews_order_item unique (order_item_id),
    constraint fk_reviews_order_item foreign key (order_item_id) references order_items (id),
    constraint ck_reviews_rating check (rating between 1 and 5)
);

-- ---------------------------------------------------------------- store
-- Single-row table (id = 1) with the store's operating settings.
create table store_settings (
    id                  smallint      primary key default 1,
    store_name          varchar(100)  not null,
    hotline             varchar(15)   not null,
    store_address       varchar(200)  not null,
    open_time           time          not null,
    close_time          time          not null,
    min_order_amount    numeric(12,2) not null default 0,
    is_accepting_orders boolean       not null default true,
    updated_at          timestamp(6)  not null,
    updated_by          bigint,
    constraint fk_store_settings_updated_by foreign key (updated_by) references users (id),
    constraint ck_store_settings_singleton check (id = 1),
    constraint ck_store_settings_hours check (close_time > open_time),
    constraint ck_store_settings_min_order check (min_order_amount >= 0)
);
create index ix_store_settings_updated_by on store_settings (updated_by);
