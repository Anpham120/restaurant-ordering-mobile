-- V3: password reset by e-mailed OTP, revocable sessions, forced password change,
-- and rules that keep promotions from annoying customers (opt-out, scheduled announcements).

-- Sessions: every JWT carries the user's token_version; bumping it (password change/reset) revokes all sessions.
alter table users add column token_version integer not null default 0;
-- Set after a manager resets the password: the user must choose a new one before using the app.
alter table users add column must_change_password boolean not null default false;
-- Customer accepts promotional notifications (order/payment notifications are always sent).
alter table users add column marketing_opt_in boolean not null default true;

-- One-time codes for "forgot password". Only a hash of the code is stored.
create table password_reset_tokens (
    id              bigint generated by default as identity primary key,
    user_id         bigint       not null,
    code_hash       varchar(100) not null,
    expires_at      timestamp(6) not null,
    failed_attempts integer      not null default 0,
    used_at         timestamp(6),
    created_at      timestamp(6) not null,
    requested_ip    varchar(45),
    constraint fk_password_reset_tokens_user foreign key (user_id) references users (id) on delete cascade,
    constraint ck_password_reset_tokens_attempts check (failed_attempts between 0 and 10),
    constraint ck_password_reset_tokens_expiry check (expires_at > created_at)
);
create index ix_password_reset_tokens_user on password_reset_tokens (user_id, created_at desc);

-- Announcing a promotion: requested during quiet hours → scheduled for the morning (announce_at);
-- announced_at records when it was actually sent.
alter table promotions add column announce_at timestamp(6);
alter table promotions add column announced_at timestamp(6);
update promotions p set announced_at = (select min(n.created_at) from notifications n where n.promotion_id = p.id);
create index ix_promotions_announce on promotions (announce_at) where announced_at is null;
create index ix_notifications_user_type on notifications (user_id, type, created_at desc);
