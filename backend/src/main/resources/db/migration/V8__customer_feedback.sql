-- V8: feedback a customer sends from the app (optionally about one of their orders) and the store's answer.
-- Answered = reply present; reply, replied_by and replied_at are set together (no separate status column to drift).
create table feedback (
    id          bigint generated by default as identity primary key,
    customer_id bigint        not null,
    order_id    bigint,
    topic       varchar(20)   not null,
    message     varchar(1000) not null,
    reply       varchar(1000),
    replied_by  bigint,
    replied_at  timestamp(6),
    created_at  timestamp(6)  not null,
    constraint fk_feedback_customer foreign key (customer_id) references users (id) on delete cascade,
    constraint fk_feedback_order foreign key (order_id) references orders (id),
    constraint fk_feedback_replied_by foreign key (replied_by) references users (id),
    constraint ck_feedback_topic check (topic in ('ORDER','FOOD','DELIVERY','APP','OTHER')),
    constraint ck_feedback_message check (length(trim(message)) > 0),
    constraint ck_feedback_reply check ((reply is null) = (replied_by is null) and (reply is null) = (replied_at is null))
);
create index ix_feedback_customer on feedback (customer_id, created_at desc);
create index ix_feedback_open on feedback (created_at) where reply is null;

-- the store is told about new feedback and the customer about the answer through the existing in-app notifications
alter table notifications drop constraint ck_notifications_type;
alter table notifications add constraint ck_notifications_type check (type in ('ORDER','PAYMENT','PROMOTION','FEEDBACK'));
