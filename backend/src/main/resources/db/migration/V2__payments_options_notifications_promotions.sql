-- V2: online payment (VietQR bank transfer confirmed by SePay webhooks), dish options (size/topping),
-- customer notifications and restaurant promotions (in-app banners).

-- ---------------------------------------------------------------- order status: waiting for a bank transfer
alter table orders drop constraint ck_orders_status;
alter table orders add constraint ck_orders_status
    check (status in ('AWAITING_PAYMENT','PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED'));
alter table order_status_history drop constraint ck_order_status_history_status;
alter table order_status_history add constraint ck_order_status_history_status
    check (status in ('AWAITING_PAYMENT','PENDING','CONFIRMED','PREPARING','READY','DELIVERING','DELIVERED','CANCELLED'));

-- ---------------------------------------------------------------- payments
-- One payment per order. The method moves from orders to payments (it is a fact of the payment).
create table payments (
    id           bigint generated by default as identity primary key,
    order_id     bigint        not null,
    method       varchar(20)   not null,
    amount       numeric(12,2) not null,
    status       varchar(20)   not null,
    expires_at   timestamp(6),                 -- deadline for a bank transfer
    paid_at      timestamp(6),
    confirmed_by bigint,                       -- staff who collected COD or confirmed a transfer by hand
    created_at   timestamp(6)  not null,
    updated_at   timestamp(6)  not null,
    constraint uk_payments_order unique (order_id),
    constraint fk_payments_order foreign key (order_id) references orders (id),
    constraint fk_payments_confirmed_by foreign key (confirmed_by) references users (id),
    constraint ck_payments_method check (method in ('COD','BANK_TRANSFER')),
    constraint ck_payments_status check (status in ('PENDING','PAID','FAILED','REFUND_PENDING','REFUNDED')),
    constraint ck_payments_amount check (amount >= 0),
    constraint ck_payments_paid_at check ((status in ('PAID','REFUND_PENDING','REFUNDED')) = (paid_at is not null)),
    constraint ck_payments_expiry check (method = 'BANK_TRANSFER' or expires_at is null)
);
create index ix_payments_confirmed_by on payments (confirmed_by);
create index ix_payments_status on payments (status, expires_at);
insert into payments (order_id, method, amount, status, paid_at, created_at, updated_at)
select o.id, 'COD',
       coalesce((select sum(i.quantity * i.unit_price) from order_items i where i.order_id = o.id), 0) - o.discount_amount + o.delivery_fee,
       case o.status when 'DELIVERED' then 'PAID' when 'CANCELLED' then 'FAILED' else 'PENDING' end,
       case o.status when 'DELIVERED' then o.updated_at end,
       o.created_at, o.updated_at
from orders o;
alter table orders drop constraint ck_orders_payment;
alter table orders drop column payment_method;

-- Every incoming bank transfer reported by SePay, matched to a payment when its content carries the payment code.
create table bank_transactions (
    id               bigint generated by default as identity primary key,
    provider         varchar(20)   not null,
    provider_txn_id  bigint        not null,
    gateway          varchar(60),
    account_number   varchar(30),
    amount           numeric(14,2) not null,
    content          varchar(500),
    reference_code   varchar(100),
    transaction_date timestamp(6),
    received_at      timestamp(6)  not null,
    payment_id       bigint,
    note             varchar(200),
    constraint uk_bank_transactions_provider_txn unique (provider, provider_txn_id),
    constraint fk_bank_transactions_payment foreign key (payment_id) references payments (id),
    constraint ck_bank_transactions_amount check (amount > 0)
);
create index ix_bank_transactions_payment on bank_transactions (payment_id);
create index ix_bank_transactions_received on bank_transactions (received_at desc);

-- Receiving account shown in the VietQR code; bank transfer is offered only when it is set.
alter table store_settings add column bank_code varchar(20);
alter table store_settings add column bank_account varchar(19);
alter table store_settings add column bank_holder varchar(80);
alter table store_settings add column transfer_timeout_minutes integer not null default 15;
alter table store_settings add constraint ck_store_settings_timeout check (transfer_timeout_minutes between 5 and 120);
alter table store_settings add constraint ck_store_settings_bank
    check ((bank_code is null) = (bank_account is null) and (bank_account is null or bank_account ~ '^[A-Za-z0-9]{4,19}$'));

-- ---------------------------------------------------------------- dish options (size, topping…)
create table option_groups (
    id           bigint generated by default as identity primary key,
    menu_item_id bigint      not null,
    name         varchar(60) not null,
    min_select   integer     not null default 0,
    max_select   integer     not null default 1,
    sort_order   integer     not null default 0,
    constraint uk_option_groups_item_name unique (menu_item_id, name),
    constraint fk_option_groups_menu_item foreign key (menu_item_id) references menu_items (id) on delete cascade,
    constraint ck_option_groups_select check (min_select >= 0 and max_select >= 1 and max_select >= min_select)
);

create table options (
    id           bigint generated by default as identity primary key,
    group_id     bigint        not null,
    name         varchar(60)   not null,
    price_delta  numeric(12,2) not null default 0,
    is_available boolean       not null default true,
    sort_order   integer       not null default 0,
    constraint uk_options_group_name unique (group_id, name),
    constraint fk_options_group foreign key (group_id) references option_groups (id) on delete cascade,
    constraint ck_options_price check (price_delta >= 0)
);
create index ix_options_group on options (group_id);

-- The cart can now hold the same dish twice with different options, so a line gets its own key.
drop table cart_items;
create table cart_items (
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null,
    menu_item_id bigint       not null,
    quantity     integer      not null,
    note         varchar(200),
    updated_at   timestamp(6) not null,
    constraint fk_cart_items_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_cart_items_menu_item foreign key (menu_item_id) references menu_items (id) on delete cascade,
    constraint ck_cart_items_quantity check (quantity between 1 and 99)
);
create index ix_cart_items_user on cart_items (user_id);
create index ix_cart_items_menu_item on cart_items (menu_item_id);

create table cart_item_options (
    cart_item_id bigint not null,
    option_id    bigint not null,
    constraint pk_cart_item_options primary key (cart_item_id, option_id),
    constraint fk_cart_item_options_line foreign key (cart_item_id) references cart_items (id) on delete cascade,
    constraint fk_cart_item_options_option foreign key (option_id) references options (id) on delete cascade
);
create index ix_cart_item_options_option on cart_item_options (option_id);

-- Options chosen for an order line, with the extra price charged at that moment.
create table order_item_options (
    order_item_id bigint        not null,
    option_id     bigint        not null,
    price_delta   numeric(12,2) not null,
    constraint pk_order_item_options primary key (order_item_id, option_id),
    constraint fk_order_item_options_line foreign key (order_item_id) references order_items (id),
    constraint fk_order_item_options_option foreign key (option_id) references options (id),
    constraint ck_order_item_options_price check (price_delta >= 0)
);
create index ix_order_item_options_option on order_item_options (option_id);

-- ---------------------------------------------------------------- promotions (restaurant campaigns shown in the app)
create table promotions (
    id           bigint generated by default as identity primary key,
    title        varchar(120) not null,
    subtitle     varchar(300),
    image_url    varchar(500) not null,
    target_type  varchar(20)  not null default 'NONE',
    menu_item_id bigint,
    category_id  bigint,
    voucher_id   bigint,
    start_at     timestamp(6),
    end_at       timestamp(6),
    sort_order   integer      not null default 0,
    is_active    boolean      not null default true,
    created_at   timestamp(6) not null,
    constraint fk_promotions_menu_item foreign key (menu_item_id) references menu_items (id),
    constraint fk_promotions_category foreign key (category_id) references categories (id),
    constraint fk_promotions_voucher foreign key (voucher_id) references vouchers (id),
    constraint ck_promotions_target check (target_type in ('NONE','MENU_ITEM','CATEGORY','VOUCHER')),
    constraint ck_promotions_target_ref check (
        (target_type = 'MENU_ITEM') = (menu_item_id is not null) and
        (target_type = 'CATEGORY')  = (category_id is not null) and
        (target_type = 'VOUCHER')   = (voucher_id is not null)),
    constraint ck_promotions_period check (start_at is null or end_at is null or end_at > start_at)
);
create index ix_promotions_menu_item on promotions (menu_item_id);
create index ix_promotions_category on promotions (category_id);
create index ix_promotions_voucher on promotions (voucher_id);

-- ---------------------------------------------------------------- notifications
create table notifications (
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null,
    type         varchar(20)  not null,
    title        varchar(120) not null,
    body         varchar(500) not null,
    order_id     bigint,
    promotion_id bigint,
    is_read      boolean      not null default false,
    created_at   timestamp(6) not null,
    constraint fk_notifications_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_notifications_order foreign key (order_id) references orders (id),
    constraint fk_notifications_promotion foreign key (promotion_id) references promotions (id) on delete set null,
    constraint ck_notifications_type check (type in ('ORDER','PAYMENT','PROMOTION'))
);
create index ix_notifications_user on notifications (user_id, is_read, created_at desc);
create index ix_notifications_order on notifications (order_id);
create index ix_notifications_promotion on notifications (promotion_id);
